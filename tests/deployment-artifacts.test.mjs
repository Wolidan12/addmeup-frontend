import assert from 'node:assert/strict'
import {readFile,readdir} from 'node:fs/promises'
const release=JSON.parse(await readFile('dist/version.json','utf8'))
assert.match(release.commit,/^([a-f0-9]{40}|unknown)$/)
assert.ok(Number.isFinite(Date.parse(release.builtAt)))
const html=await readFile('dist/index.html','utf8')
assert.ok(html.includes('/assets/index-'))
const files=await readdir('dist/assets')
const scripts=await Promise.all(files.filter(f=>f.endsWith('.js')).map(f=>readFile('dist/assets/'+f,'utf8')))
assert.ok(scripts.some(s=>s.includes('A new version is ready')))
assert.ok(scripts.every(s=>!s.includes('Live — connected to Supabase')))
assert.ok(scripts.every(s=>!s.includes('Sample profiles are still labelled Demo')))
const worker=await readFile('dist/sw.js','utf8')
assert.ok(worker.includes('NetworkFirst'))
assert.ok(worker.includes('NetworkOnly'))
assert.ok(worker.includes('danqel-navigation-v2'))
assert.ok(worker.includes('/offline.html'))
assert.ok(!worker.includes('registerNavigationRoute'))
console.log('Release marker, removed banners, update prompt and network-first navigation present in production artifacts')
